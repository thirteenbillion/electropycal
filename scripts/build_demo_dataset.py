#!/usr/bin/env python3
"""Build the shipped synthetic demo dataset: full in-vitro + in-vivo input/output trees.

The demo lets a new user run every notebook end-to-end without access to any real measurements.
It is **synthetic but not schematic**: ``electropycal.data.synthetic`` reproduces EIS/FSCV
distributions measured from the real in-vitro sessions (see ``REAL_INVITRO_STATS`` there and
``scripts/measure_invitro_stats.py``), so extracted features land in the real range.

Layout produced under ``--out`` (default ``demo/``):

    demo/
      in_vitro/
        input/   <date>_neurostring_channeltest/ , <date>_neurostring_signal/   raw PSTrace CSVs,
                 electropycal_analysis_config.json
        output/  featureset_raw.parquet + .csv, sensitivity_featureset.csv, manifest.json
      in_vivo/
        input/   <date>_neurostring_signal/<dev>_paired_{baseline,live}.csv
        output/  invivo_featureset.csv
      README.md

Usage:  python scripts/build_demo_dataset.py --out demo
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os

for _v in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS",
           "VECLIB_MAXIMUM_THREADS", "NUMEXPR_NUM_THREADS"):
    os.environ.setdefault(_v, "1")

from pathlib import Path

README = """# Synthetic demo dataset

Generated by `python scripts/build_demo_dataset.py`. Everything here is synthetic; there are no
real measurements. The generator is calibrated to statistics measured from real in-vitro
neurostring recordings, so the traces and extracted features sit in realistic ranges (peak V_ox
around 0.8 V, background around 30 uA, NormIpeak around 0.02 rising sub-linearly with dose,
noise_floor around 0.015).

| Path | What |
|------|------|
| `in_vitro/input/` | raw PSTrace exports: `*_channeltest` (0 nM screen) and `*_signal` (EIS, dose series, stabilization) folders, one per timepoint, plus `electropycal_analysis_config.json`, the shared band and QC settings the notebooks read |
| `in_vitro/output/` | what the pipeline produces from that input: the extracted featureset (not D0-normalized), the per-sensor calibration targets, and a manifest |
| `in_vivo/input/` | paired FSCV+EIS exports per session (`_paired_baseline`, `_paired_live`) for the deployment and domain-shift demo |
| `in_vivo/output/` | the in-vivo featureset extracted from it |

The notebooks find this tree on their own: leave `ROOT` at `None` and run top to bottom. To
point at it explicitly, use `demo/in_vitro/input`, or `demo/in_vivo/input` for
`deployment_domain_shift`.

Stabilization files use the `-full` spelling (6 rounds of 6 cycles), the one current
acquisition protocols produce. The generator can also emit the older `-start` and `-end` pair; see
`write_synthetic_pstrace_dir(stab_phases=...)`.

Regenerate at any time. The generator is seeded, so the output is reproducible.
"""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", default="demo")
    ap.add_argument("--band", default="2,2000")
    args = ap.parse_args(argv)

    from electropycal.analysis_config import AnalysisConfig, save_analysis_config
    from electropycal.data.synthetic import (REAL_INVITRO_STATS, write_synthetic_invivo_dir,
                                             write_synthetic_pstrace_dir)
    from electropycal.features.extract import (FEATURE_SCHEMA_VERSION, extract_dataset,
                                               extract_invivo)
    from electropycal.features.targets import sensitivity_featureset

    band = tuple(float(x) for x in args.band.split(","))
    out = Path(args.out)
    iv_in, iv_out = out / "in_vitro" / "input", out / "in_vitro" / "output"
    vv_in, vv_out = out / "in_vivo" / "input", out / "in_vivo" / "output"
    for d in (iv_in, iv_out, vv_in, vv_out):
        d.mkdir(parents=True, exist_ok=True)

    # ---- in vitro ---------------------------------------------------------------------------
    print(f"writing in-vitro raw tree -> {iv_in}")
    # Only "-full": that is the spelling current acquisition protocols produce, and the demo
    # tree is the de facto documentation of the input contract, so it should show what real
    # data looks like and exercise the branch real data takes (chosen_phases prefers "full").
    # 6 cycles/round rather than the 20-cycle default: the stabilization CSVs are the largest part
    # of the demo, and their size is linear in rounds x cycles_per_round. The 6 ROUNDS stay: the
    # convergence check needs patience=3 rounds below tol.
    #
    # 6 is a MEASURED floor, not a guess. estimate_settle_tau fits an exponential to the cycles
    # within a round, and round_average_cycles first drops each round's cold-start, so too few
    # cycles leave nothing to fit and tau blows up. Measured tau per channel, one session:
    #     3 cyc -> [2.1, 17640, 15.3, 19642]   two degenerate fits
    #     4 cyc -> [1.9, 1.4, 2726, 3.8]       one degenerate fit
    #     5 cyc -> [1.3, 3.9, 2.3, 18.3]       finite, but a 14x spread
    #     6 cyc -> [1.3, 1.4, 1.4, 5.1]        clean; comparable to 20 cyc's [0.4..0.9]
    # Below 6 cycles the demo's convergence table shows degenerate fits.
    #
    # Nothing has to be told this number: StabilizationIndex.cycle_no reads the `cycle` column
    # that stabilization_traces derives by counting, so generator and reader cannot disagree.
    write_synthetic_pstrace_dir(iv_in, stab_phases=("full",), stab_cycles_per_round=6)
    cfg = AnalysisConfig(band=band)
    try:
        save_analysis_config(iv_in, cfg)
    except Exception as e:                                  # config helper is optional
        print(f"(config save skipped: {e})")

    print("extracting in-vitro featureset ...")
    feat = extract_dataset(iv_in, band=band, d0_normalize=False, n_jobs=1, progress=False)
    feat.to_parquet(iv_out / "featureset_raw.parquet")
    feat.to_csv(iv_out / "featureset_raw.csv", index=False)
    sens = sensitivity_featureset(feat)
    sens.to_csv(iv_out / "sensitivity_featureset.csv", index=False)

    # ---- in vivo ----------------------------------------------------------------------------
    print(f"writing in-vivo raw tree -> {vv_in}")
    write_synthetic_invivo_dir(vv_in)
    try:
        iv = extract_invivo(vv_in, band=band)
        iv.to_csv(vv_out / "invivo_featureset.csv", index=False)
        n_invivo = len(iv)
    except Exception as e:
        print(f"(in-vivo extraction skipped: {e})")
        n_invivo = 0

    manifest = {
        "generated_utc": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "synthetic": True,
        "calibrated_from": "real in-vitro sessions (see synthetic.REAL_INVITRO_STATS)",
        "feature_schema_version": FEATURE_SCHEMA_VERSION,
        "band_hz": list(band),
        "counts": {"dose_rows": int(len(feat)),
                   "sensors": int(feat.groupby(["device", "channel"]).ngroups),
                   "timepoints": int(feat["timepoint"].nunique()),
                   "sensitivity_rows": int(len(sens)),
                   "invivo_rows": int(n_invivo)},
        "reference_stats": REAL_INVITRO_STATS,
    }
    (iv_out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n",
                                          encoding="utf-8")
    (out / "README.md").write_text(README, encoding="utf-8")

    print(f"\nOK: demo dataset in {out}/")
    print(f"  in-vitro: {manifest['counts']['dose_rows']} dose rows, "
          f"{manifest['counts']['sensors']} sensors, "
          f"{manifest['counts']['timepoints']} timepoints")
    print(f"  in-vivo : {n_invivo} rows")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
